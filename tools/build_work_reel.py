#!/usr/bin/env python3
"""Flatten the project galleries into one photo reel for the service pages.

Reads data/projects.js (the same file the map on the home page uses), and
writes:

  data/work-reel.js      window.PSI_REEL = { projects: [...], photos: [...] }
                         one entry per photograph, with its pixel size so the
                         reel can lay every slide out before the image loads
  assets/reel/<name>.jpg a 900px copy of each photograph for the reel itself;
                         the full-size original is what the lightbox opens

No client address appears in either output: project labels come straight
from projects.js, which carries only the type of work and the town.

Run on its own, or let tools/build-services.py call it.
"""

import json
import os
import struct
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "data", "projects.js")
OUT_JS = os.path.join(ROOT, "data", "work-reel.js")
OUT_DIR = os.path.join(ROOT, "assets", "reel")
DOMAIN = "https://psiconstructionpa.com/"
REEL_PX = 800   # longest side; the reel shows slides at most ~440px tall


def load_projects():
    """projects.js is JavaScript, not JSON; let node evaluate it."""
    js = ("const w={};global.window=w;eval(require('fs').readFileSync(%s,'utf8'));"
          "process.stdout.write(JSON.stringify(w.PSI_PROJECTS));" % json.dumps(SRC))
    return json.loads(subprocess.check_output(["node", "-e", js]))


def jpeg_size(path):
    """Width and height from the JPEG's SOF marker, without decoding it."""
    with open(path, "rb") as fh:
        data = fh.read()
    i = 2
    while i < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
            h, w = struct.unpack(">HH", data[i + 5:i + 9])
            return w, h
        i += 2 + length
    raise ValueError("no SOF marker in " + path)


def local(src):
    if src.startswith(DOMAIN):
        src = src[len(DOMAIN):]
    return src.lstrip("/")


def build():
    projects = load_projects()
    os.makedirs(OUT_DIR, exist_ok=True)
    out_projects, photos = [], []
    made = 0
    for p in projects:
        gallery = p.get("gallery") or []
        if not gallery:
            continue
        pi = len(out_projects)
        out_projects.append({
            "id": p["id"],
            "title": p.get("title") or p.get("name") or "",
            "city": p.get("city") or "",
            # One blurb refers to "this page" meaning the home page.
            "desc": (p.get("desc") or "").replace(" Featured in the aerial opener on this page.", ""),
        })
        for g in gallery:
            rel = local(g["src"])
            full = os.path.join(ROOT, rel)
            if not os.path.exists(full):
                sys.exit("missing photograph: " + rel)
            name = os.path.basename(rel)
            small = os.path.join(OUT_DIR, name)
            if not os.path.exists(small):
                # ffmpeg's mjpeg encoder at q5 lands near 60KB a photograph;
                # sips needed more than twice that for the same picture.
                fit = "scale='if(gt(iw,ih),%d,-2)':'if(gt(iw,ih),-2,%d)'" % (REEL_PX, REEL_PX)
                subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", full,
                                "-vf", fit, "-q:v", "5", small], check=True)
                made += 1
            w, h = jpeg_size(small)
            photos.append([pi, name, w, h, g.get("phase") or "", g.get("cap") or "", "/" + rel])
    # Remove reel copies for photographs that are no longer in any gallery.
    keep = {ph[1] for ph in photos}
    for f in os.listdir(OUT_DIR):
        if f.endswith(".jpg") and f not in keep:
            os.remove(os.path.join(OUT_DIR, f))
    body = json.dumps({"dir": "/assets/reel/", "projects": out_projects, "photos": photos},
                      ensure_ascii=False, separators=(",", ":"))
    with open(OUT_JS, "w") as fh:
        fh.write("/* Generated by tools/build_work_reel.py from data/projects.js — do not edit.\n"
                 "   photos: [project index, file, width, height, phase, caption, full-size path] */\n"
                 "window.PSI_REEL = " + body + ";\n")
    print("reel  %d photographs from %d jobs (%d reel copies made) -> data/work-reel.js"
          % (len(photos), len(out_projects), made))
    return photos


if __name__ == "__main__":
    build()
